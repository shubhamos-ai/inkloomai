export function generateMockHistoryItem(result: AnalysisResult): AnalysisHistoryItem {
  const critical = result.violations.filter((v) => v.severity === 'critical').length;
  const major = result.violations.filter((v) => v.severity === 'major').length;
  const minor = result.violations.filter((v) => v.severity === 'minor').length;
  return {
    id: result.id,
    advertisementName: result.advertisementName,
    thumbnailUrl: result.imageUrl,
    analysedAt: result.analysedAt,
    complianceScore: result.complianceScore,
    complianceLevel: result.complianceLevel,
    status: result.status,
    violationsCount: result.violations.length,
    criticalCount: critical,
    majorCount: major,
    minorCount: minor,
  };
}
